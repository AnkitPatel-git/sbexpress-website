                            <h3>Packaging Guidelines </h3>
                        </div><!-- .custom-heading end -->
                        <b>STEP BY STEP PROCEDURE : </b> 
                        <ol>
                          <li>Use a corrugated box or a rigid carton. Check the weight specification of the box / carton you are using and don't exceed its capacity.</li>
                          <li>Wrap the items separately.</li>
                         
                          <li>Provide internal protection with adequate cushioning material.</li>
                          <li>Use strong tape designed for shipping. Tape should be at least 2" wide, but preferably 3" wide. </li>
                          <li>Use proper labeling that has a clear and complete origin & destination address, including phone numbers and pin codes.</li>
                          
                          
                        </ol><br/>
                         <b>SOME PACKING SUGGESTIONS  : </b> 
                        <ol>
                          
                          <li>For floppy disks the packing must be in padded envelopes or in blister- proof packing.</li>
                          <li>Sample medical vials must have adequate protection inside the packing so that the same do not move. Shredded paper can be used for packing such materials</li>
                          <li>Gutka</li>
                          <li>For foodstuff samples like, Tea, Rice, Grains, Pulses, etc. fabric-reinforced envelopes must be used. Plain covers should not be used.</li>
                          <li>Books must be packed in cartons / wooden cases. If in cartons, two strappings must be done to ensure that the contents hold together.</li>
                          <li>Textile goods must be first wrapped in polythene or any suitable waterproof material and then covered with strong Hessian / Jute cloth.</li>
                          <li>Electronic articles must be packed in adequate-ply corrugated cartons.</li>
                          
                        </ol><br/>
                        <b>VOLUMETRIC CALCULATAION :</b>
                        <p>Volumetric weight is a standard practice followed throughout the air-freight industry that considers density determining charges.<br/>
                        The calculations are used to consider the amount of space a package will take in various modes of transportation / warehouse in relation to the actual weight of the package.</p>
